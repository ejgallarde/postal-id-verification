-- Every verification attempt, successful or not.
--
-- prn_hash is SHA-256 over (pepper || normalized PRN). The raw PRN is never
-- persisted here and never written to logs, so the audit trail supports
-- rate-limit forensics and abuse investigation without becoming a second
-- copy of the identifier it is protecting.
--
-- failure_reason_code records WHY a verification failed. This detail exists
-- only in this table: the API response says nothing beyond INVALID, so the
-- endpoint cannot be used as an oracle to probe which field was wrong.

CREATE TABLE verification_audit (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id          VARCHAR(36)  NOT NULL,
    client_id           VARCHAR(100),
    principal           VARCHAR(120),
    channel             VARCHAR(16)  NOT NULL,
    result              VARCHAR(16)  NOT NULL,
    failure_reason_code VARCHAR(32),
    prn_hash            VARCHAR(64)  NOT NULL,
    matched_record_id   VARCHAR(32),
    remote_ip           VARCHAR(45),
    user_agent          VARCHAR(255),
    created_at          TIMESTAMP    NOT NULL
);

CREATE INDEX idx_audit_prn_hash  ON verification_audit (prn_hash, created_at);
CREATE INDEX idx_audit_client    ON verification_audit (client_id, created_at);
CREATE INDEX idx_audit_created   ON verification_audit (created_at);
