-- One row per Postal ID enrollment record, sourced from *_demographics.csv.
-- Portable ANSI SQL: verified against both H2 and PostgreSQL.

CREATE TABLE cardholder (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Identity ------------------------------------------------------------
    -- record_id is the packet join key and the filename prefix of every asset
    -- (AC + ERD + StID + SQNo). postal_ref_no is the number printed on the card
    -- and is what a verifying user actually types in.
    record_id               VARCHAR(32)   NOT NULL,
    postal_ref_no           VARCHAR(32)   NOT NULL,
    rnum                    VARCHAR(32),
    control_no              VARCHAR(32),

    -- Name ----------------------------------------------------------------
    first_name              VARCHAR(120)  NOT NULL,
    middle_name             VARCHAR(120),
    last_name               VARCHAR(120)  NOT NULL,
    suffix_name             VARCHAR(32),

    -- Normalized name forms written by the ingester using the same
    -- FieldNormalizer the verifier uses, so matching never transforms at query time.
    first_name_norm         VARCHAR(120)  NOT NULL,
    middle_name_norm        VARCHAR(120),
    last_name_norm          VARCHAR(120)  NOT NULL,

    -- Vitals --------------------------------------------------------------
    gender                  VARCHAR(8),
    date_of_birth           DATE          NOT NULL,
    civil_status            VARCHAR(8),
    nationality             VARCHAR(64),
    height                  VARCHAR(16),
    weight                  VARCHAR(16),
    complexion              VARCHAR(32),
    hair_color              VARCHAR(32),
    eye_color               VARCHAR(32),
    distinguishing_features VARCHAR(255),

    -- Place of birth ------------------------------------------------------
    pob_city                VARCHAR(160),
    pob_province            VARCHAR(64),
    pob_country             VARCHAR(8),

    -- Parents -------------------------------------------------------------
    father_first_name       VARCHAR(120),
    father_middle_name      VARCHAR(120),
    father_last_name        VARCHAR(120),
    father_suffix_name      VARCHAR(32),
    mother_first_name       VARCHAR(120),
    mother_middle_name      VARCHAR(120),
    mother_last_name        VARCHAR(120),
    mother_suffix_name      VARCHAR(32),

    -- Home address --------------------------------------------------------
    addr_postal_code        VARCHAR(16),
    addr_country            VARCHAR(8),
    addr_province           VARCHAR(64),
    addr_city               VARCHAR(160),
    addr_area               VARCHAR(255),
    addr_barangay           VARCHAR(64),
    addr_subdivision        VARCHAR(64),
    addr_street             VARCHAR(64),
    addr_house_bldg_lot     VARCHAR(64),

    -- Work ----------------------------------------------------------------
    company_name            VARCHAR(255),
    occupation              VARCHAR(160),
    work_postal_code        VARCHAR(16),
    work_country            VARCHAR(8),
    work_province           VARCHAR(64),
    work_city               VARCHAR(160),
    work_area               VARCHAR(255),
    work_barangay           VARCHAR(64),
    work_subdivision        VARCHAR(64),
    work_street             VARCHAR(64),
    work_house_bldg_lot     VARCHAR(64),

    -- Contact -------------------------------------------------------------
    contact_no              VARCHAR(64),
    mobile_no               VARCHAR(64),
    email                   VARCHAR(120),

    -- Government identifiers ----------------------------------------------
    tin                     VARCHAR(32),
    crn                     VARCHAR(32),
    gsis                    VARCHAR(32),
    philhealth              VARCHAR(32),
    hdmf                    VARCHAR(32),

    -- Enrollment ----------------------------------------------------------
    branch                  VARCHAR(16),
    area_code               VARCHAR(16),
    enrollment_date         DATE,
    station_id              VARCHAR(32),
    sequence_no             VARCHAR(16),
    card_type               VARCHAR(8),
    process_type            VARCHAR(8),
    enroll_reason           VARCHAR(64),
    entry_type              VARCHAR(8),
    mail_option             VARCHAR(16),
    issuing_post_office     VARCHAR(64),
    apo_code                VARCHAR(16),
    cpo_code                VARCHAR(16),
    sched_date              DATE,

    -- Payment -------------------------------------------------------------
    or_number               VARCHAR(32),
    or_date                 DATE,
    or_branch               VARCHAR(64),
    or_amount               DECIMAL(12, 2),

    -- Record state --------------------------------------------------------
    -- demo_status mirrors the terminal row of card_status_history. Verification
    -- gates on this: a record merely existing is not proof that a card was issued.
    demo_status             VARCHAR(8),
    is_deleted              BOOLEAN       NOT NULL DEFAULT FALSE,
    done_qa                 VARCHAR(8),
    qa_tag                  VARCHAR(32),
    captured_by             VARCHAR(64),
    time_start_capture      VARCHAR(32),
    time_end_capture        VARCHAR(32),

    -- Audit ---------------------------------------------------------------
    created_at              TIMESTAMP     NOT NULL,
    updated_at              TIMESTAMP     NOT NULL,

    CONSTRAINT uq_cardholder_record_id     UNIQUE (record_id),
    CONSTRAINT uq_cardholder_postal_ref_no UNIQUE (postal_ref_no)
);

-- Primary verification lookup path.
CREATE INDEX idx_cardholder_prn_lookup ON cardholder (postal_ref_no, is_deleted, demo_status);
CREATE INDEX idx_cardholder_name_norm  ON cardholder (last_name_norm, first_name_norm);
