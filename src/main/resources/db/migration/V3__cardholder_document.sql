-- Maps one enrollment record to the many files captured with it (requirement 3).
--
-- Two storage kinds, because the packet's contents divide sharply in how they are used:
--
--   MANAGED  - the bytes are copied into the blob store under storage_path and served on
--              demand. Only the photograph and signature, which is what the API can serve
--              and therefore what has to be immediately available. Roughly 1% of a packet.
--   EXTERNAL - metadata and a pointer only; the bytes stay wherever they already live.
--              Birth and marriage certificates, receipts, forms and fingerprints. No route
--              can serve these, so copying them would duplicate the bulk of every packet
--              into a tier that never reads it.
--
-- source_path is relative to the ingest source root, not absolute, so an archive that is
-- later moved or remounted stays resolvable: archive root + source_path. sha256 is recorded
-- for every file regardless of kind, so an archived document can still be checked against
-- what was captured.

CREATE TABLE cardholder_document (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cardholder_id     BIGINT       NOT NULL,
    doc_code          VARCHAR(16)  NOT NULL,
    original_filename VARCHAR(255) NOT NULL,

    storage_kind      VARCHAR(16)  NOT NULL,
    -- Path within the blob store. Null for EXTERNAL documents, which were never copied.
    storage_path      VARCHAR(512),
    -- Where the file sat at ingest, relative to the ingest source root. Always recorded.
    source_path       VARCHAR(1024),

    content_type      VARCHAR(64)  NOT NULL,
    byte_size         BIGINT       NOT NULL,
    sha256            VARCHAR(64)  NOT NULL,
    captured_at       TIMESTAMP,
    created_at        TIMESTAMP    NOT NULL,
    updated_at        TIMESTAMP    NOT NULL,

    CONSTRAINT fk_document_cardholder FOREIGN KEY (cardholder_id)
        REFERENCES cardholder (id) ON DELETE CASCADE,
    CONSTRAINT fk_document_type FOREIGN KEY (doc_code)
        REFERENCES document_type (code),
    CONSTRAINT uq_document_per_cardholder UNIQUE (cardholder_id, doc_code),

    -- A MANAGED document without bytes would 404 at serve time; catch it at write time.
    CONSTRAINT ck_document_managed_has_path
        CHECK (storage_kind <> 'MANAGED' OR storage_path IS NOT NULL)
);

CREATE INDEX idx_document_cardholder ON cardholder_document (cardholder_id);
CREATE INDEX idx_document_storage_kind ON cardholder_document (storage_kind);
