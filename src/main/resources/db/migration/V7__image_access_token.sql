-- Short-lived capability references handed out only on a VALID verification.
--
-- Only the SHA-256 of the reference is stored, so a database read cannot be
-- replayed against the image endpoint. Each row is bound to one cardholder,
-- one document code and the client that earned it; expiry and a use counter
-- stop the reference becoming a durable handle to someone's photograph.

CREATE TABLE image_access_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash     VARCHAR(64) NOT NULL,
    cardholder_id  BIGINT      NOT NULL,
    doc_code       VARCHAR(16) NOT NULL,
    client_id      VARCHAR(100),
    issued_at      TIMESTAMP   NOT NULL,
    expires_at     TIMESTAMP   NOT NULL,
    uses_remaining INTEGER     NOT NULL,
    revoked        BOOLEAN     NOT NULL DEFAULT FALSE,

    CONSTRAINT uq_image_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_image_token_cardholder FOREIGN KEY (cardholder_id)
        REFERENCES cardholder (id) ON DELETE CASCADE,
    CONSTRAINT fk_image_token_doc_type FOREIGN KEY (doc_code)
        REFERENCES document_type (code)
);

CREATE INDEX idx_image_token_expiry ON image_access_token (expires_at);
