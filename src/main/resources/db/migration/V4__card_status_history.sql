-- Enrollment status trail from *__demostatusdtl.csv (REC -> AQC -> FAF -> STA -> QOK -> FCD -> CDE).

CREATE TABLE card_status_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cardholder_id    BIGINT      NOT NULL,
    source_id        BIGINT,
    status           VARCHAR(16) NOT NULL,
    status_timestamp TIMESTAMP,
    processed_by     VARCHAR(64),

    CONSTRAINT fk_status_cardholder FOREIGN KEY (cardholder_id)
        REFERENCES cardholder (id) ON DELETE CASCADE
);

CREATE INDEX idx_status_cardholder ON card_status_history (cardholder_id, status_timestamp);
