<#
.SYNOPSIS
    Starts the PIVOT sandbox and publishes it on the internet through a Cloudflare quick tunnel.

.DESCRIPTION
    1. Creates %USERPROFILE%\.pivot-sandbox\sandbox.env on first run, filled with freshly generated
       secrets, and restricts it to the current Windows account. Later runs reuse it, so testers'
       credentials survive a restart.
    2. Opens a quick tunnel (cloudflared) and reads the public https://*.trycloudflare.com URL it
       is given.
    3. Starts the sandbox profile bound to 127.0.0.1, with that URL as the token issuer, and waits
       until the synthetic data is loaded.

    A quick tunnel needs no Cloudflare account, but its URL changes every time it starts and it
    comes with no uptime guarantee. For a fixed address, see "A permanent address" in
    docs/SANDBOX.md.

.PARAMETER Stop
    Stops a sandbox and tunnel started by this script.

.PARAMETER Port
    Local port for the sandbox. Default 8080.

.EXAMPLE
    mvn -DskipTests package
    powershell -ExecutionPolicy Bypass -File scripts\sandbox.ps1

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\sandbox.ps1 -Stop
#>
param(
    [switch]$Stop,
    [int]$Port = 8080
)

$ErrorActionPreference = 'Stop'

$repoRoot  = Split-Path -Parent $PSScriptRoot
$stateDir  = Join-Path $env:USERPROFILE '.pivot-sandbox'
$envFile   = Join-Path $stateDir 'sandbox.env'
$pidFile   = Join-Path $stateDir 'pids.txt'
$urlFile   = Join-Path $stateDir 'public-url.txt'
$tunnelLog = Join-Path $stateDir 'tunnel.log'
$appLog    = Join-Path $stateDir 'sandbox.log'
$appErrLog = Join-Path $stateDir 'sandbox-err.log'

function Stop-Sandbox {
    if (-not (Test-Path $pidFile)) {
        Write-Host 'No sandbox started by this script is recorded as running.'
        return
    }
    foreach ($id in Get-Content $pidFile) {
        try { Stop-Process -Id ([int]$id) -Force -ErrorAction Stop; Write-Host "Stopped process $id" } catch { }
    }
    Remove-Item $pidFile, $urlFile -ErrorAction SilentlyContinue
}

function Test-Running {
    if (-not (Test-Path $pidFile)) { return $false }
    foreach ($id in Get-Content $pidFile) {
        if (-not (Get-Process -Id ([int]$id) -ErrorAction SilentlyContinue)) { return $false }
    }
    return $true
}

# URL-safe base64 of cryptographically random bytes: no characters that need escaping in a
# Basic auth header, a form post, or this env file.
function New-Secret([int]$Bytes = 32) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buffer).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Initialize-Secrets {
    if (Test-Path $envFile) { return }

    New-Item -ItemType Directory -Force -Path $stateDir | Out-Null
    @(
        '# PIVOT sandbox secrets. Generated by scripts\sandbox.ps1; readable by this account only.'
        '# Share SANDBOX_TESTER_SECRET and SANDBOX_TESTER_CONSOLE_PASSWORD with testers over a'
        '# separate channel from the URL. Delete this file to rotate everything on the next start.'
        "POSTALID_AUDIT_PRN_HASH_PEPPER=$(New-Secret 32)"
        "SANDBOX_TESTER_SECRET=$(New-Secret 32)"
        "SANDBOX_TESTER_CONSOLE_PASSWORD=$(New-Secret 18)"
        "SANDBOX_ADMIN_PASSWORD=$(New-Secret 24)"
    ) | Set-Content -Path $envFile -Encoding ASCII

    # Owner-only: remove inherited permissions and grant the current user alone.
    icacls $envFile /inheritance:r /grant:r "$($env:USERNAME):(R,W)" | Out-Null
    Write-Host "Generated new sandbox secrets in $envFile"
}

function Import-Secrets {
    foreach ($line in Get-Content $envFile) {
        if ($line -match '^\s*#' -or $line -notmatch '=') { continue }
        $name, $value = $line -split '=', 2
        Set-Item -Path "env:$($name.Trim())" -Value $value.Trim()
    }
}

function Find-Java {
    if ($env:JAVA_HOME -and (Test-Path (Join-Path $env:JAVA_HOME 'bin\java.exe'))) {
        return Join-Path $env:JAVA_HOME 'bin\java.exe'
    }
    $adoptium = Get-ChildItem 'C:\Program Files\Eclipse Adoptium' -Directory -Filter 'jdk-25*' -ErrorAction SilentlyContinue |
            Sort-Object Name -Descending | Select-Object -First 1
    if ($adoptium) { return Join-Path $adoptium.FullName 'bin\java.exe' }
    $onPath = Get-Command java -ErrorAction SilentlyContinue
    if ($onPath) { return $onPath.Source }
    throw 'No Java 25 runtime found. Install a JDK 25 or set JAVA_HOME.'
}

function Find-Cloudflared {
    $onPath = Get-Command cloudflared -ErrorAction SilentlyContinue
    if ($onPath) { return $onPath.Source }
    $wingetLink = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links\cloudflared.exe'
    if (Test-Path $wingetLink) { return $wingetLink }
    # A user-scope winget install may leave the binary in its package folder with no link on PATH
    # until the next sign-in.
    $wingetPackage = Get-ChildItem (Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages') -Directory `
            -Filter 'Cloudflare.cloudflared_*' -ErrorAction SilentlyContinue |
            ForEach-Object { Get-ChildItem $_.FullName -Filter 'cloudflared*.exe' -ErrorAction SilentlyContinue } |
            Select-Object -First 1
    if ($wingetPackage) { return $wingetPackage.FullName }
    throw 'cloudflared not found. Install it with: winget install --id Cloudflare.cloudflared -e --scope user'
}

function Wait-ForLine([string]$Path, [string]$Pattern, [int]$TimeoutSeconds, [string]$FailPattern) {
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        if (Test-Path $Path) {
            $text = Get-Content $Path -Raw -ErrorAction SilentlyContinue
            if ($text) {
                $match = [regex]::Match($text, $Pattern)
                if ($match.Success) { return $match.Value }
                if ($FailPattern -and [regex]::IsMatch($text, $FailPattern)) { return $null }
            }
        }
        Start-Sleep -Milliseconds 500
    }
    return $null
}

if ($Stop) {
    Stop-Sandbox
    return
}

if (Test-Running) {
    Write-Host "The sandbox is already running at $(Get-Content $urlFile -ErrorAction SilentlyContinue)"
    Write-Host 'Run with -Stop first to restart it.'
    return
}

$jar = Get-ChildItem (Join-Path $repoRoot 'target') -Filter 'postal-id-verification-*.jar' -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -notlike '*.original' } | Select-Object -First 1
if (-not $jar) { throw "No built jar in $repoRoot\target. Run: mvn -DskipTests package" }

$java = Find-Java
$cloudflared = Find-Cloudflared
Initialize-Secrets
Import-Secrets
Remove-Item $tunnelLog, $appLog, $appErrLog -ErrorAction SilentlyContinue

# 1. The tunnel first: its URL becomes the issuer stamped into every token the sandbox signs.
Write-Host 'Opening a Cloudflare quick tunnel...'
$tunnel = Start-Process -FilePath $cloudflared -WindowStyle Hidden -PassThru `
        -ArgumentList @('tunnel', '--no-autoupdate', '--url', "http://127.0.0.1:$Port") `
        -RedirectStandardError $tunnelLog
$publicUrl = Wait-ForLine $tunnelLog 'https://[a-z0-9-]+\.trycloudflare\.com' 60 'failed to request quick Tunnel'
if (-not $publicUrl) {
    Stop-Process -Id $tunnel.Id -Force -ErrorAction SilentlyContinue
    throw "The tunnel did not come up. See $tunnelLog"
}

# 2. The sandbox, on loopback only; the tunnel is the one way in.
$env:POSTALID_ISSUER = $publicUrl
$env:SERVER_PORT = "$Port"
Write-Host 'Starting the sandbox and loading synthetic data...'
$app = Start-Process -FilePath $java -WindowStyle Hidden -PassThru -WorkingDirectory $repoRoot `
        -ArgumentList @('-Duser.timezone=UTC', '-jar', "`"$($jar.FullName)`"", '--spring.profiles.active=sandbox') `
        -RedirectStandardOutput $appLog -RedirectStandardError $appErrLog

@($tunnel.Id, $app.Id) | Set-Content $pidFile
$publicUrl | Set-Content $urlFile

$ready = Wait-ForLine $appLog 'Sandbox ready: \d+ synthetic cardholder' 180 'APPLICATION FAILED TO START|Refusing to start'
if (-not $ready) {
    Stop-Sandbox
    throw "The sandbox did not start. See $appLog"
}

Write-Host ''
Write-Host '  PIVOT sandbox is live' -ForegroundColor Green
Write-Host "  Web console   $publicUrl/            (user: tester, password: SANDBOX_TESTER_CONSOLE_PASSWORD)"
Write-Host "  API           $publicUrl/api/v1/verify"
Write-Host "  Token         $publicUrl/oauth2/token  (client: sandbox-tester, secret: SANDBOX_TESTER_SECRET)"
Write-Host "  API docs      $publicUrl/swagger-ui.html"
Write-Host ''
Write-Host "  Credentials   $envFile"
Write-Host "  Logs          $stateDir"
Write-Host '  Stop          scripts\sandbox.ps1 -Stop'
Write-Host ''
Write-Host '  The address changes each time the tunnel restarts, and this machine must stay on and awake.' -ForegroundColor Yellow
